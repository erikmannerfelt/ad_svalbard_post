"""Validation summary for the ArcticDEM strip outlier ("gap") classifier.

`processing_ADSvalbard`'s `evaluate_gap_model_grouped()` runs patch-grouped
(`StratifiedGroupKFold` on `patch_id`) cross-validation of the classifier's training
procedure, replacing the old point-level `train_test_split` that let pixels from the
same labelled polygon leak between train and test. See that function's docstring for
the full rationale. This module turns its four result CSVs, shipped in
`input/aux_files.zip`, into the `\\dataXclassifierX...` statistics macros and the
Supporting Information importance table.

There is no cheaper way to validate the exact deployed model instead of the training
procedure: re-running strip-level outlier masking would cost roughly 20 days of
downstream reprocessing. The grouped-CV numbers here are therefore the only
classifier validation this project has, not a preview pending something more direct
-- word manuscript text accordingly (grouped by labelled polygon, not by strip).
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

from . import tools
from .config import TABLE_DIR

SCORES_SUMMARY_FILE: Final = "gap_model_grouped_cv_scores_summary.csv"
IMPORTANCE_SUMMARY_FILE: Final = "gap_model_grouped_cv_importance_summary.csv"

#: CV metric names that contain a digit and so can't be used as `reporting.to_tex_macros`
#: keys (TeX control sequences must be letters only).
_METRIC_KEY_OVERRIDES: Final[dict[str, str]] = {"f1": "f_score"}


def get_classifier_stats() -> dict[str, object]:
    """Summarise the gap classifier's grouped cross-validation for `tables/statistics.tex`.

    Reads the two `*_summary.csv` aux files (mean/std already aggregated across the 5
    folds) rather than the per-fold files, since the manuscript only cites the
    aggregate. The two most important features are also identified here so their
    importance values can be cited by macro; which two they are is currently
    `npi_dh` (elevation difference to the reference DEM) and `gap_distance`, and is
    stated as prose in the manuscript rather than as a macro, since a feature name
    containing an underscore cannot be spliced into a TeX macro value directly. If
    `aux_files.zip` is ever regenerated with a materially different labelled dataset,
    re-check that this ranking -- and therefore the prose naming it -- still holds.

    Returns
    -------
    A dict with `scores` (mean/std of each CV metric) and `importance` (name and
    mean/std importance of the top two features), matching the nesting
    `statistics.get_statistics()` merges under `all_stats["classifier"]`.
    """
    scores = tools.read_aux_csv(SCORES_SUMMARY_FILE, index_col=0)
    importance = tools.read_aux_csv(IMPORTANCE_SUMMARY_FILE, index_col=0).sort_values(
        "mean", ascending=False
    )

    scores_out: dict[str, float] = {}
    for metric, row in scores.iterrows():
        key = _METRIC_KEY_OVERRIDES.get(str(metric), str(metric))
        scores_out[f"{key}_mean"] = float(row["mean"])
        scores_out[f"{key}_std"] = float(row["std"])

    top_two = importance.iloc[:2]
    importance_out = {
        "top_feature_importance_mean": float(top_two.iloc[0]["mean"]),
        "top_feature_importance_std": float(top_two.iloc[0]["std"]),
        "second_feature_importance_mean": float(top_two.iloc[1]["mean"]),
        "second_feature_importance_std": float(top_two.iloc[1]["std"]),
    }

    return {"scores": scores_out, "importance": importance_out}


def write_classifier_importance_table() -> Path:
    """Write the SI gap-classifier permutation-importance table to `tables/classifier_importance.tex`.

    Every row comes straight from `gap_model_grouped_cv_importance_summary.csv` in
    `aux_files.zip`, so the table cannot drift from the grouped-CV result it reports.
    Feature names are the raw model column names (`npi_dh`, `gap_distance`, the
    `quadric_*` quadratic/Horn slope coefficients, etc.) set in `\\texttt{}` with
    underscores escaped for TeX.
    """
    importance = tools.read_aux_csv(IMPORTANCE_SUMMARY_FILE, index_col=0).sort_values(
        "mean", ascending=False
    )

    lines = [
        "% Autogenerated by src.gap_classifier.write_classifier_importance_table -- do not edit.",
        r"\begin{tabular}{lrr}",
        r"\hline",
        r"\textbf{Feature} & \textbf{Importance (mean)} & \textbf{Importance (std)} \\",
        r"\hline",
    ]
    for name, row in importance.iterrows():
        escaped_name = str(name).replace("_", r"\_")
        lines.append(f"\\texttt{{{escaped_name}}} & {row['mean']:.4f} & {row['std']:.4f} \\\\")
    lines += [r"\hline", r"\end{tabular}"]

    path = TABLE_DIR / "classifier_importance.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path
